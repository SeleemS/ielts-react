function Table({ caption, head, rows, firstColumnHeader = true }) {
  return (
    <div className="overflow-hidden rounded-xl border border-border bg-card shadow-sm">
      <div className="overflow-x-auto">
        <table className="w-full border-collapse text-left text-sm">
          <caption className="border-b border-border bg-muted/50 px-4 py-3 text-left text-sm font-semibold text-foreground">
            {caption}
          </caption>
          <thead>
            <tr className="border-b border-border bg-muted/30">
              {head.map((h) => (
                <th
                  key={h}
                  scope="col"
                  className="whitespace-nowrap px-4 py-2.5 text-xs font-semibold uppercase tracking-wide text-muted-foreground"
                >
                  {h}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((row) => (
              <tr key={row[0]} className="border-b border-border align-top last:border-b-0">
                {row.map((cell, i) =>
                  i === 0 && firstColumnHeader ? (
                    <th
                      key={i}
                      scope="row"
                      className="whitespace-nowrap px-4 py-2.5 text-left font-semibold text-foreground"
                    >
                      {cell}
                    </th>
                  ) : (
                    <td key={i} className="whitespace-nowrap px-4 py-2.5 text-muted-foreground">
                      {cell}
                    </td>
                  )
                )}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

